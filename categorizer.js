// ── Build DEFAULT_CATEGORIES from dictionary ────────────────────────
const DEFAULT_CATEGORIES = categoryDictionary;

// ── Domain lookup map (built once for O(1) access) ──────────────────
const _DOMAIN_MAP = (() => {
  const map = {};
  for (const cat of DEFAULT_CATEGORIES) {
    for (const d of (cat.domains || [])) map[d] = cat;
  }
  return map;
})();

// Walk up subdomain chain: sub.foo.bar.com → foo.bar.com → bar.com
function _matchDomain(hostname) {
  if (!hostname) return null;
  if (_DOMAIN_MAP[hostname]) return _DOMAIN_MAP[hostname];
  const parts = hostname.split('.');
  for (let i = 1; i < parts.length - 1; i++) {
    const parent = parts.slice(i).join('.');
    if (_DOMAIN_MAP[parent]) return _DOMAIN_MAP[parent];
  }
  return null;
}

// ── Parse & clean text for matching ─────────────────────────────────
function _cleanText(...sources) {
  return sources
    .filter(Boolean)
    .join(' ')
    .toLowerCase()
    .replace(/[^a-z0-9\s./:@#\-_+]/g, ' ')
    .replace(/\s+/g, ' ');
}

// ── Full classify (uses page signals when available) ────────────────
// ALWAYS returns a category object — never null/undefined.
function classifyTab(signals, url, custom = []) {
  const customCats = (custom || []).map(c => ({ ...c, weight: 1.5 }));
  const all = [...customCats, ...DEFAULT_CATEGORIES];

  // 1. Domain exact/subdomain match (highest confidence)
  let hostname = '';
  try { hostname = new URL(url).hostname.replace(/^www\./, ''); } catch(e) {}
  if (hostname) {
    for (const cat of all) {
      if ((cat.domains || []).some(d => hostname === d || hostname.endsWith('.' + d)))
        return cat;
    }
  }

  // 2. Score by page signals + keywords
  const text = _cleanText(
    signals.title, signals.description, signals.keywords,
    signals.h1, signals.ogSiteName, url
  );

  let best = null, top = 0;
  for (const cat of all) {
    let s = 0;
    for (const kw of (cat.keywords || [])) { if (text.includes(kw)) s += 2; }
    s *= (cat.weight || 1);
    if (s > top) { top = s; best = cat; }
  }
  if (top >= 4) return best;

  // 3. STRICT FALLBACK — never return null
  return FALLBACK_CATEGORY;
}